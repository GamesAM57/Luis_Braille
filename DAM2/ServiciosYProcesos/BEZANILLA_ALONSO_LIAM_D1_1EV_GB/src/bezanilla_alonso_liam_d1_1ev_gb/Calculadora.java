    private void resultadoOperaciones(){
        if(op.equals("=")){
            pantallaResultados.setText(" = "+resultado);
        } else if (op.equals("+")){
            resultado = n1 +n2;
            pantallaResultados.setText(pantallaResultados+"+");
        } else if (op.equals("-")){
            resultado = n1 -n2;
            pantallaResultados.setText(pantallaResultados+"-");
        } else if (op.equals("*")){
            resultado = n1 *n2;
            pantallaResultados.setText(pantallaResultados+"*");
        } else if (op.equals("/")){
            resultado = n1 /n2;
            pantallaResultados.setText(pantallaResultados+"/");
        }
    }
    
    private void mostrarGuardarNumero(int n){
        if (op.isBlank()){
            n1 = n;
            pantallaResultados.setText(""+n);
        }
        else{
            n2 = n;
            resultadoOperaciones();
        }
            
        
        numeroSeleccionado.setText(""+n);
        
    }
